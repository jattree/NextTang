#!/usr/bin/env python3
"""Add NextTang's SerDes status and clock taps to a Gowin-generated serdes.v.

usage: patch_serdes.py path/to/src/serdes/serdes.v      (edits the file in place)

The SerDes wrapper (module SerDes_Top) is generated by the Gowin IP generator
and stays out of Git. top_pcie_dma.v expects three extra outputs on it:
  nt_probe[31:0], nt_probe2[7:0]  lane-0 and quad status for ltssm_uart3
  nt_clk[6:0]                     quad clocks; nt_clk[0] is the PCIe REFCLK
                                  (q0_fabric_cmu_ck_ref_o) that nt_serdes_reinit
                                  measures
Every wire used already exists in the generated file; the patch only adds the
ports and three assigns. Running it twice is refused.
"""
import re
import sys

ASSIGNS = """
// NextTang: lane-0 SerDes status and quad clocks (tools/patch_serdes.py)
assign nt_probe = {q0_fabric_ln0_stat_o[12:0], q0_fabric_ln0_astat_o[5:0], q0_lane0_disp_err_o[1:0], q0_lane0_dec_err_o[1:0],
    q0_fabric_ln0_rxelecidle_o, q0_lane0_k_lock, q0_lane0_align_link, q0_fabric_ln0_pma_rx_lock_o,
    q0_fabric_ln0_rxdet_result, q0_fabric_pma_cm0_dr_refclk_det_o, q0_fabric_cmu_ok_o};
assign nt_probe2 = {q0_fabric_refclk_gate_ack_o, q0_fabric_cmu_refclk_gate_ack_o, q0_fabric_cmu1_refclk_gate_ack_o,
    q0_fabric_pma_cm1_dr_refclk_det_o, q0_fabric_cmu1_ok_o, q0_fabric_ln0_rxelecidle_o_h, 2'b00};
assign nt_clk = {q0_fabric_cmu1_clk, q0_fabric_cmu0_clk, q0_lane0_pcs_tx_o_fabric_clk, q0_lane0_pcs_rx_o_fabric_clk,
    q0_fabric_lane0_cmu_ck_ref_o, q0_fabric_cmu1_ck_ref_o, q0_fabric_cmu_ck_ref_o};
"""
WIRES = ['q0_fabric_ln0_stat_o', 'q0_fabric_ln0_astat_o', 'q0_lane0_disp_err_o', 'q0_lane0_dec_err_o',
         'q0_fabric_ln0_rxelecidle_o', 'q0_lane0_k_lock', 'q0_lane0_align_link', 'q0_fabric_ln0_pma_rx_lock_o',
         'q0_fabric_ln0_rxdet_result', 'q0_fabric_pma_cm0_dr_refclk_det_o', 'q0_fabric_cmu_ok_o',
         'q0_fabric_refclk_gate_ack_o', 'q0_fabric_cmu_refclk_gate_ack_o', 'q0_fabric_cmu1_refclk_gate_ack_o',
         'q0_fabric_pma_cm1_dr_refclk_det_o', 'q0_fabric_cmu1_ok_o', 'q0_fabric_ln0_rxelecidle_o_h',
         'q0_fabric_cmu1_clk', 'q0_fabric_cmu0_clk', 'q0_lane0_pcs_tx_o_fabric_clk', 'q0_lane0_pcs_rx_o_fabric_clk',
         'q0_fabric_lane0_cmu_ck_ref_o', 'q0_fabric_cmu1_ck_ref_o', 'q0_fabric_cmu_ck_ref_o']


def main(argv):
    if len(argv) != 1:
        sys.exit(__doc__)
    path = argv[0]
    src = open(path, encoding='utf-8').read()
    if 'nt_clk' in src:
        sys.exit('%s already has the NextTang taps' % path)
    missing = [w for w in WIRES if not re.search(r'^wire\b[^;]*\b%s\b' % w, src, re.M)]
    if missing:
        sys.exit('not a PCIe SerDes_Top from Gowin 1.9.12.03? missing wires: %s' % ', '.join(missing))
    head = re.search(r'module SerDes_Top \(([^)]*)\);', src)
    if not head:
        sys.exit('module SerDes_Top header not found')
    src = src[:head.end(1)] + ', nt_probe, nt_probe2, nt_clk' + src[head.end(1):]
    decl = '\n// NextTang: status and clock taps\noutput [31:0] nt_probe;\noutput [7:0] nt_probe2;\noutput [6:0] nt_clk;\n'
    end_head = src.index(';', head.start()) + 1
    src = src[:end_head] + decl + src[end_head:]
    tail = src.rindex('endmodule')
    src = src[:tail] + ASSIGNS.lstrip('\n') + src[tail:]
    open(path, 'w', encoding='utf-8').write(src)
    print('%s: added nt_probe, nt_probe2, nt_clk' % path)


if __name__ == '__main__':
    main(sys.argv[1:])
