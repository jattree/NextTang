#!/usr/bin/env python3
"""Make nt_serdes_reinit_rom.vh from the PCIe IP's serdes.csr.

usage: csr_rom.py path/to/src/serdes/serdes.csr > path/to/include/nt_serdes_reinit_rom.vh

serdes.csr is generated by the Gowin IP generator with the SerDes/PCIe IP and
stays out of Git like the rest of the IP. Every write is kept, in file order,
including repeats (reset then release). Gowin 1.9.12.03 spells some lines
"upar_wirte_driver"; they are writes too and are kept.
"""
import re
import sys

LINE = re.compile(r'upar_w[a-z]*_driver\(\s*0x([0-9a-fA-F]+)\s*,\s*0x([0-9a-fA-F]+)\s*\)')


def main(argv):
    if len(argv) != 1:
        sys.exit(__doc__)
    writes = []
    with open(argv[0], encoding='utf-8') as f:
        for n, ln in enumerate(f, 1):
            if not ln.strip():
                continue
            m = LINE.search(ln)
            if not m:
                sys.exit('%s:%d: not a upar write: %s' % (argv[0], n, ln.strip()))
            a, v = int(m.group(1), 16), int(m.group(2), 16)
            if a >> 24 or v >> 32:
                sys.exit('%s:%d: address or value out of range' % (argv[0], n))
            writes.append((a, v))
    if not 0 < len(writes) <= 511:
        sys.exit('%d writes: expected 1..511' % len(writes))
    out = sys.stdout
    out.write('// Generated by boards/console138k/pcie-pi5/tools/csr_rom.py from %s: %d writes.\n'
              % (argv[0].split('/')[-1], len(writes)))
    out.write("localparam [8:0] NW = 9'd%d;\n" % len(writes))
    out.write('function [55:0] wrom(input [8:0] i);\n    case (i)\n')
    for i, (a, v) in enumerate(writes):
        out.write("        9'd%d: wrom = {24'h%06X, 32'h%08X};\n" % (i, a, v))
    out.write("        default: wrom = 56'd0;\n    endcase\nendfunction\n")


if __name__ == '__main__':
    main(sys.argv[1:])
